-- 관심도 프로필과 웹 추천 결과 (FDG-8)
CREATE TABLE interest_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(16) NOT NULL,
    value VARCHAR(128) NOT NULL,
    seed_weight DOUBLE PRECISION NOT NULL,
    learned_weight DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_interest_profile UNIQUE (kind, value)
);

CREATE TABLE feed_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_item_id BIGINT NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    matched_terms JSONB,
    popular BOOLEAN NOT NULL,
    scoring_version VARCHAR(16) NOT NULL,
    recommended_at TIMESTAMPTZ NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_feed_item UNIQUE (raw_item_id),
    CONSTRAINT fk_feed_item_raw_item FOREIGN KEY (raw_item_id) REFERENCES raw_item (id)
);

CREATE INDEX idx_feed_item_score ON feed_item (score DESC);
